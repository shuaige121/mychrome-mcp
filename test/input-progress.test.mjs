import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';

const source = await readFile(new URL('../src/index.js', import.meta.url), 'utf8');
const start = source.indexOf('function progressFor(');
const end = source.indexOf('/** One tool call,', start);
const progressFor = vm.runInNewContext(source.slice(start, end) + '\nprogressFor');
const delivered = [];
const controller = new AbortController();
const extra = { signal: controller.signal, sendNotification: async value => delivered.push(JSON.parse(JSON.stringify(value))) };
assert.equal(progressFor({ params: {} }, extra), null);
assert.equal(progressFor({ params: { _meta: { progressToken: {} } } }, extra), null);
assert.equal(progressFor({ params: { _meta: { progressToken: 1 } } }, {}), null);
const progress = progressFor({ params: { _meta: { progressToken: 'fixture' } } }, extra);
await progress(40, 500);
await progress(40, 500);
await progress(39, 500);
await progress(600, 500);
await progress(NaN, 500);
await progress(80, 500);
assert.deepEqual(delivered.map(x => x.params.progress), [40, 80]);
assert.deepEqual(delivered[0], { method: 'notifications/progress', params: { progressToken: 'fixture', progress: 40, total: 500 } });
await progress(81, 500, '预计约 75 秒（当前速度 2×）');
assert.deepEqual(delivered.at(-1).params, { progressToken: 'fixture', progress: 81, total: 500, message: '预计约 75 秒（当前速度 2×）' });
delivered.pop();
controller.abort();
await progress(120, 500);
assert.equal(delivered.length, 2);
const unavailable = progressFor({ params: { _meta: { progressToken: 0 } } }, { sendNotification: async () => { throw new Error('offline'); } });
await unavailable(1, 2);
console.log('input-progress: token, counts, privacy, cancellation and notification failure passed');
